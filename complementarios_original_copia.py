# 3. Ajustar distribución GPD
def nll(par, y):
    xi, s = par
    if s <= 1e-9 or (1 + xi*y/s <= 0).any():
        return 1e9
    z = 1 + xi*y/s
    if abs(xi) < 1e-7:
        return len(y)*np.log(s) + np.sum(y/s)
    return len(y)*np.log(s) + (1 + 1/xi)*np.log(z).sum()

def ajustar(y, inicio=((0.2, 0.007), (0.05, 0.009), (0.3, 0.006))):
    resultados = [minimize(nll, x, args=(y,), method="Nelder-Mead",
                           options={"maxiter": 5000, "xatol": 1e-10})
                  for x in inicio]
    return min(resultados, key=lambda r: r.fun).x

# 4. Calcular VaR y ES
def riesgo(xi, s, u, n, nu):
    var = u + s/xi * (((n/nu)*(1-P))**(-xi)-1)
    es = (var + s - xi*u)/(1-xi)
    return var, es

def pesos(x):
    return V*(1-np.exp(-x))/1e6

def estimar(L, q):
    u = np.quantile(L, q)
    y = L[L > u] - u
    xi, s = ajustar(y)
    var, es = riesgo(xi, s, u, len(L), len(y))
    return u, len(y), xi, s, var, es

