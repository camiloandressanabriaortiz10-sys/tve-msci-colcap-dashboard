# 5.2 Bootstrap
u, nu, xi, s, var, es = estimar(L, 0.90)
y = L[L > u] - u
rng = np.random.default_rng(SEMILLA)
sim = []

for _ in range(REPLICAS):
    yb = rng.choice(y, len(y), replace=True)
    xb, sb = ajustar(yb, inicio=((xi, s), (0.05, 0.009)))
    vb, eb = riesgo(xb, sb, u, len(L), len(y))
    sim.append((xb, vb, eb))

sim = np.array(sim)

print(f"\n2) Bootstrap ({REPLICAS} réplicas), intervalo al 95 %")

for j, nombre in enumerate(("xi", "VaR 99 %", "ES 99 %")):
    lo, hi = np.percentile(sim[:, j], [2.5, 97.5])
    if j == 0:
        print(f"{nombre}: {lo:.2f} - {hi:.2f}")
    else:
        print(f"{nombre}: {lo:.2%} - {hi:.2%} "
              f"(COP {pesos(lo):.1f} - {pesos(hi):.1f} mill.)")

